-- Радар (16.10): бани, которые нашёл еженедельный локальный прогон агентов (OpenStreetMap, 2ГИС, Яндекс, сайты бань),
-- с «индексом общественности» 0–100. Видит только Комиссия, и только она решает: завести в лигу, привязать к нашей бане
-- (у той точка неточная — переносим), скрыть (не баня, аренда, дубль). Без её решения на карту лиги ничего не попадает.
-- Пишет сюда только прогон (scripts/radar/push.py → supabase db query), по стабильному ключу места; решения Комиссии
-- при следующей заливке не затираются.
create table public.radar_places (
  id bigint generated by default as identity primary key,
  key text not null unique,                        -- osm:n123 / 2gis:7000… / name:… — одно место между прогонами
  region text, name text not null, city text, address text,
  lat double precision, lng double precision,      -- null — точку не нашли (у источника была заглушка)
  website text, map_url text,
  kind text check (kind in ('public', 'spa', 'private', 'other', 'closed', 'unknown')),
  public_index int check (public_index between 0 and 100),
  confidence text check (confidence in ('high', 'medium', 'low')),
  gender_split boolean, ticket_per_person boolean, price_example text,
  note text,                                       -- почему агент так решил, одной фразой
  evidence jsonb not null default '[]',            -- [{quote, url}] — короткие цитаты с сайтов бань
  league_hint bigint references public.baths(id) on delete set null,   -- название совпало с этой баней лиги
  status text not null default 'new' check (status in ('new', 'added', 'matched', 'hidden')),
  bath_id bigint references public.baths(id) on delete set null,       -- заведённая или привязанная баня
  decided_by uuid references public.players(id), decided_at timestamptz,
  first_seen timestamptz not null default now(), last_seen timestamptz not null default now()
);
alter table public.radar_places enable row level security;
create policy "Радар видит Комиссия" on public.radar_places for select to authenticated using (public.is_commission());
revoke all on public.radar_places from anon, authenticated;   -- на стенде права раздаются по умолчанию — снимаем явно
grant select on public.radar_places to authenticated;
grant all on public.radar_places to service_role;

-- решение Комиссии по месту: add — завести общественной баней с точной точкой (страну и регион по точке дольёт
-- ночной разбор ebl-fill-places); match — это наша баня p_bath (точку сайт переносит обычным путём, bath-location);
-- hide — скрыть; reopen — вернуть в «новые»
create function public.radar_decide(p_id bigint, p_action text, p_bath bigint default null) returns bigint
language plpgsql security definer set search_path = public as $$
declare r public.radar_places; v_bath bigint;
begin
  if not public.is_commission() then raise exception 'Решает только Комиссия'; end if;
  select * into r from public.radar_places where id = p_id for update;
  if not found then raise exception 'Места нет в радаре'; end if;
  if p_action = 'add' then
    if r.status = 'added' and r.bath_id is not null then return r.bath_id; end if;   -- двойное нажатие — та же баня
    insert into public.baths (name, type, lat, lng, precision, status, created_by)
    values (r.name, 'public', r.lat, r.lng, case when r.lat is null then null else 'exact' end, 'ok', public.me())
    returning id into v_bath;
    update public.radar_places set status = 'added', bath_id = v_bath, decided_by = public.me(), decided_at = now() where id = p_id;
    return v_bath;
  elsif p_action = 'match' then
    if p_bath is null or not exists (select 1 from public.baths where id = p_bath) then raise exception 'Нет такой бани в лиге'; end if;
    update public.radar_places set status = 'matched', bath_id = p_bath, decided_by = public.me(), decided_at = now() where id = p_id;
    return p_bath;
  elsif p_action = 'hide' then
    update public.radar_places set status = 'hidden', decided_by = public.me(), decided_at = now() where id = p_id;
  elsif p_action = 'reopen' then
    update public.radar_places set status = 'new', bath_id = null, decided_by = null, decided_at = null where id = p_id;
  else
    raise exception 'Неизвестное действие %', p_action;
  end if;
  return null;
end $$;
revoke execute on function public.radar_decide(bigint, text, bigint) from public;
grant execute on function public.radar_decide(bigint, text, bigint) to authenticated, service_role;
