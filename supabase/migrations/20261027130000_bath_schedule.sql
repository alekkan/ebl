-- Пары и часы работы бани (27.10): вносит любой участник в карточке бани на сайте. Как цены — история, а не текущее
-- состояние: каждая правка новой строкой, в силе последняя своего вида; если ничего не изменилось — строку не пишем.
-- Пары — список времени (14:00, 15:00…): «каждый час» и «каждые два часа» сайт сам раскладывает из «с — до», а every_min
-- помнит, как вносили; «другое» — часы, которые участник отметил сам. Часы работы — открытие и закрытие (закрытие раньше
-- открытия — работает за полночь, одинаковые — круглосуточно).
create table public.bath_schedule (
  id bigint generated by default as identity primary key,
  bath_id bigint not null references public.baths(id) on delete cascade,
  kind text not null check (kind in ('steam', 'hours')),
  times time[] check (cardinality(times) between 1 and 48),
  every_min int check (every_min in (60, 120)),
  open_time time,
  close_time time,
  created_by uuid references public.players(id),
  created_at timestamptz not null default now(),
  check (kind = 'steam' and times is not null and open_time is null and close_time is null
      or kind = 'hours' and times is null and every_min is null and open_time is not null and close_time is not null)
);
create index on public.bath_schedule (bath_id, kind, id desc);

alter table public.bath_schedule enable row level security;
create policy "расписание видно всем" on public.bath_schedule for select using (true);
create policy "Комиссия удаляет неверное расписание" on public.bath_schedule for delete to authenticated using (public.is_commission());

grant select on public.bath_schedule to anon, authenticated;
grant delete on public.bath_schedule to authenticated;

create function public.submit_bath_steam(p_bath_id bigint, p_times time[], p_every_min int) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_me uuid := public.me();
  v_times time[];
  v_last bath_schedule;
  v_id bigint;
begin
  if v_me is null then raise exception 'Расписание могут вносить участники лиги'; end if;
  if not exists (select 1 from baths where id = p_bath_id and status <> 'rejected') then
    raise exception 'Нет такой бани';
  end if;
  if p_every_min is not null and p_every_min not in (60, 120) then raise exception 'Пары — каждый час или каждые два часа'; end if;
  select array_agg(distinct t order by t) into v_times from unnest(p_times) t where t is not null;
  if v_times is null then raise exception 'Отметь хотя бы один пар'; end if;
  if cardinality(v_times) > 48 then raise exception 'Слишком много паров'; end if;

  select * into v_last from bath_schedule where bath_id = p_bath_id and kind = 'steam' order by id desc limit 1;
  if v_last.id is not null and v_last.times = v_times and v_last.every_min is not distinct from p_every_min then
    return null;   -- расписание не изменилось — новую запись не пишем
  end if;

  insert into bath_schedule (bath_id, kind, times, every_min, created_by)
  values (p_bath_id, 'steam', v_times, p_every_min, v_me)
  returning id into v_id;
  return v_id;
end $$;

create function public.submit_bath_hours(p_bath_id bigint, p_open time, p_close time) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_me uuid := public.me();
  v_last bath_schedule;
  v_id bigint;
begin
  if v_me is null then raise exception 'Часы работы могут вносить участники лиги'; end if;
  if not exists (select 1 from baths where id = p_bath_id and status <> 'rejected') then
    raise exception 'Нет такой бани';
  end if;
  if p_open is null or p_close is null then raise exception 'Нужны время открытия и закрытия'; end if;

  select * into v_last from bath_schedule where bath_id = p_bath_id and kind = 'hours' order by id desc limit 1;
  if v_last.id is not null and v_last.open_time = p_open and v_last.close_time = p_close then
    return null;
  end if;

  insert into bath_schedule (bath_id, kind, open_time, close_time, created_by)
  values (p_bath_id, 'hours', p_open, p_close, v_me)
  returning id into v_id;
  return v_id;
end $$;

-- карточка просит расписание одной бани, когда её открыли (как bath_facts) — первый экран не тяжелеет
create function public.bath_schedule_of(p_bath bigint) returns json
language sql stable security definer
set search_path = ''
as $$
  select json_build_object(
    'steam', (select json_build_object('times', (select json_agg(to_char(t, 'HH24:MI') order by t) from unnest(s.times) t),
                'every_min', s.every_min, 'at', s.created_at)
              from public.bath_schedule s where s.bath_id = p_bath and s.kind = 'steam' order by s.id desc limit 1),
    'hours', (select json_build_object('open', to_char(s.open_time, 'HH24:MI'), 'close', to_char(s.close_time, 'HH24:MI'), 'at', s.created_at)
              from public.bath_schedule s where s.bath_id = p_bath and s.kind = 'hours' order by s.id desc limit 1))
$$;

revoke all on function public.submit_bath_steam(bigint, time[], int) from public, anon;
grant execute on function public.submit_bath_steam(bigint, time[], int) to authenticated;
revoke all on function public.submit_bath_hours(bigint, time, time) from public, anon;
grant execute on function public.submit_bath_hours(bigint, time, time) to authenticated;
revoke execute on function public.bath_schedule_of(bigint) from public;
grant execute on function public.bath_schedule_of(bigint) to anon, authenticated, service_role;
