-- Перенести точную точку бани: участник предлагает — Комиссия решает (обещание лиге 14.10). Точная точка бывает неверной:
-- у Рублевских она пришла из первой выгрузки таблицы и стояла в Подольске, а Диман прислал верные координаты — и бот,
-- и сайт ему отказали («поменять может Комиссия»). Теперь такая точка — запрос: Комиссии в личку старая и новая точки
-- с кнопками «Перенести» / «Оставить». Примерную точку участник по-прежнему ставит сам, Комиссия — любую сама.
create table public.bath_point_requests (
  id bigint generated by default as identity primary key,
  bath_id bigint not null references public.baths(id) on delete cascade,
  lat double precision not null, lng double precision not null,
  old_lat double precision, old_lng double precision,      -- что стояло, когда просили: Комиссия видит обе точки
  requested_by uuid not null references public.players(id),
  source text not null check (source in ('site', 'bot')),
  tg_chat bigint, tg_msg bigint,                             -- сообщение с точкой в чате: после решения бот ставит реакцию
  status text not null default 'pending' check (status in ('pending', 'ok', 'rejected')),
  decided_by uuid references public.players(id), decided_at timestamptz,
  messages jsonb not null default '[]',                      -- уведомления Комиссии [{chat, msg}] — правим после решения
  created_at timestamptz not null default now()
);
create index on public.bath_point_requests (bath_id) where status = 'pending';
alter table public.bath_point_requests enable row level security;
grant all on public.bath_point_requests to service_role;     -- пишут и читают только функции (bath-location, бот)

-- новый запрос — сразу Комиссии в личку (tg-bot?pointreq=<id>); ждём бота до 30 с (pg_net по умолчанию — 5)
create function public.notify_point_request() returns trigger
language plpgsql security definer set search_path = public as $$
declare base text := (select value #>> '{}' from settings where key = 'functions_url');
begin
  if base is not null then
    perform net.http_post(url := base || '/tg-bot?pointreq=' || new.id, headers := '{"Content-Type": "application/json"}'::jsonb,
      body := '{}'::jsonb, timeout_milliseconds := 30000);
  end if;
  return new;
end $$;
create trigger bath_point_requests_notify after insert on public.bath_point_requests
for each row execute function public.notify_point_request();
