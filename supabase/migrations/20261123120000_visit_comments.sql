-- Комментарии к походам в ленте (23.11): пишут и читают только участники лиги — как саму ленту.
-- Только текст до 500 знаков, без правки: свой удаляет автор, любой — Комиссия.
create table public.visit_comments (
  id bigint generated by default as identity primary key,
  visit_id bigint not null references public.visits(id) on delete cascade,
  player_id uuid not null references public.players(id),
  text text not null check (char_length(btrim(text)) between 1 and 500),
  created_at timestamptz not null default now()
);
create index on public.visit_comments (visit_id, created_at);

alter table public.visit_comments enable row level security;
create policy "комментарии — для участников лиги" on public.visit_comments for select to authenticated using (public.me() is not null);
create policy "комментарий пишу от себя" on public.visit_comments for insert to authenticated with check (player_id = public.me());
create policy "свой комментарий или Комиссия удаляет" on public.visit_comments for delete to authenticated
  using (player_id = public.me() or public.is_commission());
-- время и номер ставит база: в запросе их не задать
revoke all on public.visit_comments from anon, authenticated;   -- на стенде права раздаются по умолчанию — снимаем явно
grant select, delete on public.visit_comments to authenticated;
grant insert (visit_id, player_id, text) on public.visit_comments to authenticated;
grant all on public.visit_comments to service_role;
