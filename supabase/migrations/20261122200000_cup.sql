-- команды собираются заново на каждый тур: кто с кем и на каком пути
create table public.cup_teams (
  id int generated by default as identity primary key,
  round int not null references public.cup_rounds(n),
  num int not null,
  path text not null default 'champions' check (path in ('champions', 'losers')),
  unique (round, num)
);
create table public.cup_team_players (
  team_id int not null references public.cup_teams(id) on delete cascade,
  player_id uuid not null references public.players(id),
  primary key (team_id, player_id)
);
create index on public.cup_team_players (player_id);

-- очки кубка по походам — пишет только recompute (cup_apply)
create table public.cup_points (
  visit_id bigint not null references public.visits(id) on delete cascade,
  nick text not null,
  round int not null references public.cup_rounds(n),
  team_id int not null references public.cup_teams(id) on delete cascade,
  total int not null,
  lines jsonb not null default '[]',
  primary key (visit_id, nick)
);
create index on public.cup_points (round);

alter table public.cup_rounds enable row level security;
alter table public.cup_teams enable row level security;
alter table public.cup_team_players enable row level security;
alter table public.cup_points enable row level security;
create policy "туры кубка видны всем" on public.cup_rounds for select using (true);
create policy "команды кубка видны всем" on public.cup_teams for select using (true);
create policy "составы кубка видны всем" on public.cup_team_players for select using (true);
-- по походам — как журнал: только участникам лиги; гостю — суммы через cup_state()
create policy "очки кубка по походам — для участников лиги" on public.cup_points for select to authenticated using (public.me() is not null);
grant select on public.cup_rounds, public.cup_teams, public.cup_team_players to anon, authenticated;
grant select on public.cup_points to authenticated;
grant all on public.cup_rounds, public.cup_teams, public.cup_team_players, public.cup_points to service_role;

