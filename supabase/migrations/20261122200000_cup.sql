create function public.cup_apply(p_points jsonb) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(hashtext('ebl:cup'));
  delete from cup_points where true;
  -- поход или команду могли удалить, пока шёл расчёт — пропускаем, а не роняем запись
  insert into cup_points (visit_id, nick, round, team_id, total, lines)
  select r.visit_id, r.nick, r.round, r.team_id, r.total, r.lines
  from jsonb_populate_recordset(null::cup_points, p_points) r
  where exists (select 1 from visits v where v.id = r.visit_id) and exists (select 1 from cup_teams t where t.id = r.team_id);
end $$;
revoke all on function public.cup_apply(jsonb) from public, anon, authenticated;
grant execute on function public.cup_apply(jsonb) to service_role;

-- всё о кубке для сайта одним json: туры, команды, очки участников по турам (суммы — без дат и бань, их видят только участники)
create function public.cup_state() returns json
language sql stable security definer set search_path = public as $$
  select json_build_object(
    'rounds', (select coalesce(json_agg(json_build_object('n', r.n, 'starts_at', r.starts_at, 'ends_at', r.ends_at) order by r.n), '[]'::json) from cup_rounds r),
    'teams', (select coalesce(json_agg(json_build_object('id', t.id, 'round', t.round, 'num', t.num, 'path', t.path,
                'players', (select coalesce(json_agg(p.nick order by p.nick), '[]'::json)
                            from cup_team_players tp join players p on p.id = tp.player_id where tp.team_id = t.id))
                order by t.round, t.num), '[]'::json) from cup_teams t),
    'points', (select coalesce(json_agg(json_build_object('round', x.round, 'nick', x.nick, 'total', x.total, 'baths', x.baths)), '[]'::json)
               from (select round, nick, sum(total) as total, count(*) filter (where total > 0) as baths from cup_points group by round, nick) x),
    'long_gate', (select value from settings where key = 'long_confirm')
  )
$$;
revoke all on function public.cup_state() from public;
grant execute on function public.cup_state() to anon, authenticated, service_role;

-- кубок — в общий запрос первого экрана (новых запросов при загрузке не плодим)
create or replace function public.boot_public(apikey text default null) returns json
language sql stable
set search_path = ''
as $$
  select json_build_object(
    'baths', public.baths_all(),
    'counts', public.bath_counts_all(),
    'standings', (select coalesce(json_agg(s order by s.nick), '[]'::json) from public.standings s),
    'reviews', (select coalesce(json_agg(json_build_object('id', r.id, 'bath_id', r.bath_id, 'rating', r.rating, 'text', r.text,
                  'created_at', r.created_at, 'player_id', r.player_id, 'players', case when p.id is null then null else json_build_object('nick', p.nick) end)
                  order by r.id), '[]'::json)
                from public.reviews r left join public.players p on p.id = r.player_id),
    'prices', (select coalesce(json_agg(json_build_object('id', x.id, 'bath_id', x.bath_id, 'price', x.price, 'currency', x.currency,
                 'duration_min', x.duration_min, 'is_weekend', x.is_weekend, 'before_time', x.before_time, 'price_date', x.price_date)
                 order by x.bath_id, x.price_date, x.id), '[]'::json)
               from public.bath_prices x),
    'beer', (select coalesce(json_agg(json_build_object('id', x.id, 'bath_id', x.bath_id, 'price', x.price, 'currency', x.currency, 'price_date', x.price_date)
               order by x.bath_id, x.price_date, x.id), '[]'::json)
             from public.bath_beer_prices x),
    'players', (select coalesce(json_agg(json_build_object('id', p.id, 'nick', p.nick, 'is_commission', p.is_commission, 'photo_url', p.photo_url)
                  order by p.id), '[]'::json)
                from public.players p),
    'cup', public.cup_state()
  )
$$;
