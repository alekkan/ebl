-- «Среднеточно» (19.10, решение владельца): точка, которую геокодер OpenStreetMap нашёл по названию бани при запуске
-- портала (26.09, scripts/geocode.py) и которую никто не проверял. Раньше она считалась «точной», но бывает не та баня
-- (Рублевские, 14.10; в Радаре «наша точка» оказывалась в 30–70 км). Теперь 'auto': на карте — как примерная (без разноса),
-- «знаю, где это» поправит любой участник без заявки Комиссии, в каталог Парсовета не идёт (он берёт только точные).
-- Точной становится, когда точку поставил человек: сайт, бот, Радар или Комиссия.
alter table public.baths drop constraint baths_precision_check;
alter table public.baths add constraint baths_precision_check check (precision in ('exact', 'auto', 'city', 'region', 'country'));

