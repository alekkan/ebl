-- Сверка каталога (19.10): агенты прошли общественные бани лиги по 2ГИС, Яндекс Картам, OpenStreetMap и сайтам бань
-- (docs/catalog.md) и предлагают по каждой точку, адрес, ссылки и факты для портала (часы, мужские и женские дни, цену).
-- Видит и решает только Комиссия, как в Радаре: «Принять» ставит найденную точку точной, «Оставить нашу» — точку не
-- трогаем, факты принимаем, «Отклонить» — с причиной. Уверенные можно принять одной пачкой. Регион Комиссии не меняем —
-- расхождение только показываем. Пишет сюда только заливка прогона (scripts/catalog/push.py → supabase db query).
create table public.catalog_proposals (
  id bigint generated by default as identity primary key,
  run text not null,                                   -- дата прогона, '2026-10-19'
  bath_id bigint not null references public.baths(id) on delete cascade,
  found_name text, address text, city text,
  region_found text, region_conflict boolean not null default false,   -- регион по карточке не тот, что у Комиссии
  lat double precision, lng double precision,          -- null — координат в источниках нет (у японских бань часто)
  point_src text,                                      -- 2gis / yandex / osm / site
  match int check (match between 0 and 100),          -- индекс уверенности: та ли это баня
  match_why text,
  bin text,                                            -- confirm / new / move / notfound / region — как разложил build.py
  website text, yandex_url text, twogis_url text, phone text,
  place_status text check (place_status in ('open', 'closed', 'repair', 'unknown')),
  is_public boolean, public_why text,
  hours text, gender_days text, price text, price_date text, price_src text,
  sections jsonb not null default '[]', amenities jsonb not null default '[]',
  evidence jsonb not null default '[]',                -- [{quote, url}] — короткие цитаты с сайтов бань
  note text,                                           -- что важно Комиссии, одной фразой
  status text not null default 'new' check (status in ('new', 'accepted', 'kept', 'rejected')),
  reject_reason text check (reject_reason in ('other_bath', 'wrong_point', 'not_public', 'closed', 'duplicate', 'other')),
  prev_lat double precision, prev_lng double precision, prev_precision text,   -- точка до «Принять» — для «Отменить» ('none' — точки не было)
  decided_by uuid references public.players(id), decided_at timestamptz,
  created_at timestamptz not null default now(),
  unique (run, bath_id)
);
alter table public.catalog_proposals enable row level security;
create policy "Сверку видит Комиссия" on public.catalog_proposals for select to authenticated using (public.is_commission());
revoke all on public.catalog_proposals from anon, authenticated;   -- на стенде права раздаются по умолчанию — снимаем явно
grant select on public.catalog_proposals to authenticated;
grant all on public.catalog_proposals to service_role;

-- решение Комиссии по одной или пачке предложений; возвращает, сколько решено.
-- accept — найденная точка становится точной (если наша точная и ближе 300 м — оставляем нашу: её ставил человек);
-- keep — точку не трогаем, данные принимаем; reject — с причиной; reopen — вернуть в разбор (точку после accept
-- возвращаем прежнюю, если баню с тех пор никто не двигал)
create function public.catalog_decide(p_ids bigint[], p_action text, p_reason text default null) returns int
language plpgsql security definer set search_path = public as $$
declare r public.catalog_proposals; b public.baths; n int := 0; far double precision;
begin
  if not public.is_commission() then raise exception 'Решает только Комиссия'; end if;
  if p_action not in ('accept', 'keep', 'reject', 'reopen') then raise exception 'Неизвестное действие %', p_action; end if;
  for r in select * from public.catalog_proposals where id = any(p_ids) order by id for update loop
    if p_action = 'reopen' then
      if r.status = 'new' then continue; end if;
      if r.status = 'accepted' and r.prev_precision is not null then
        update public.baths set lat = r.prev_lat, lng = r.prev_lng, precision = nullif(r.prev_precision, 'none')
        where id = r.bath_id and lat = r.lat and lng = r.lng;
      end if;
      update public.catalog_proposals set status = 'new', reject_reason = null, prev_lat = null, prev_lng = null,
        prev_precision = null, decided_by = null, decided_at = null where id = r.id;
      n := n + 1; continue;
    end if;
    if r.status <> 'new' then continue; end if;   -- уже решено (двойное нажатие, пачка поверх решённого)
    if p_action = 'accept' and r.lat is not null then
      select * into b from public.baths where id = r.bath_id for update;
      far := case when b.lat is null then null else 6371 * 2 * asin(sqrt(power(sin(radians(r.lat - b.lat) / 2), 2)
        + cos(radians(b.lat)) * cos(radians(r.lat)) * power(sin(radians(r.lng - b.lng) / 2), 2))) end;
      if b.lat is null or b.precision is distinct from 'exact' or far > 0.3 then
        update public.catalog_proposals set prev_lat = b.lat, prev_lng = b.lng, prev_precision = coalesce(b.precision, 'none') where id = r.id;
        update public.baths set lat = r.lat, lng = r.lng, precision = 'exact' where id = r.bath_id;
      end if;
    end if;
    update public.catalog_proposals set status = case p_action when 'accept' then 'accepted' when 'keep' then 'kept' else 'rejected' end,
      reject_reason = case when p_action = 'reject' then coalesce(p_reason, 'other') end,
      decided_by = public.me(), decided_at = now() where id = r.id;
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function public.catalog_decide(bigint[], text, text) from public;
grant execute on function public.catalog_decide(bigint[], text, text) to authenticated, service_role;
