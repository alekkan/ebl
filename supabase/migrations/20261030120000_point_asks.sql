-- Сверка, «Не нашли» (30.10, просьба Лехи): бот спрашивает в личке тех, кто был, где баня. Одна баня в день на человека,
-- чтобы не пугать списком; кнопки «🤷 Не помню», «🙅 Не был там», «🔕 Не спрашивай». Точка ответом на вопрос — запрос
-- Комиссии (bath_point_requests, как перенос точки), Комиссия решает в личке. Подробно — docs/catalog.md.
create table public.point_asks (
  id bigint generated by default as identity primary key,
  bath_id bigint not null references public.baths(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  -- sent — ждём ответа; point — прислал точку (решает Комиссия); forgot / not_there / stop — кнопки;
  -- skipped — три дня молчал: баню спросим у другого, его — о следующей
  status text not null default 'sent' check (status in ('sent', 'point', 'forgot', 'not_there', 'stop', 'skipped')),
  tg_chat bigint, tg_msg bigint,
  request_id bigint references public.bath_point_requests(id) on delete set null,
  sent_at timestamptz not null default now(),
  answered_at timestamptz,
  unique (bath_id, player_id)
);
create index on public.point_asks (tg_chat, tg_msg);
alter table public.point_asks enable row level security;
grant all on public.point_asks to service_role;   -- пишет и читает только бот

alter table public.players add column no_point_asks boolean not null default false;   -- нажал «🔕 Не спрашивай»

-- кому слать: "off" — никому, ["Леха"] — только этим (проба), "all" — всем, кто был
insert into public.settings (key, value) values ('point_asks', '"off"') on conflict (key) do nothing;

-- раз в день в 12:00 по Москве; бот сам решает, кому и о чём (повторный вызов в тот же день ничего не шлёт)
select cron.schedule('ebl-point-asks', '0 9 * * *', $$
  select net.http_post(
    url := (select value #>> '{}' from public.settings where key = 'functions_url') || '/tg-bot?asks=1',
    headers := '{"Content-Type": "application/json"}'::jsonb, body := '{}'::jsonb, timeout_milliseconds := 60000)
$$);

-- кого о чём можно спросить: бани из «Не нашли» (как вкладка Сверки: агенты не уверены, не «Тип», «Регион», «Флажки»),
-- у которых точка всё ещё не точная и запрос Комиссии не ждёт решения; кто там был — походы сезона и прошлых (legacy_visits).
-- Одним json: строк бывает больше 1000
create function public.point_ask_candidates() returns jsonb
language sql stable security definer set search_path = public as $$
  with doubt as (
    select distinct p.bath_id from catalog_proposals p join baths b on b.id = p.bath_id
    where p.status = 'new' and coalesce(p.match, 0) < 70 and not p.region_conflict and p.is_public is not false
      and coalesce(p.place_status, 'open') not in ('closed', 'repair')
      and not (coalesce(p.kind_found, '') = 'public' and b.type is distinct from 'public')
      and not (coalesce(p.kind_found, '') in ('spa', 'private') and b.type is null)
      and b.precision is distinct from 'exact'
      and not exists (select 1 from bath_point_requests r where r.bath_id = p.bath_id and r.status = 'pending')
  ), was as (
    select v.bath_id, vp.player_id, count(*)::int n, max(extract(year from v.entered_at))::int last
    from visits v join visit_players vp on vp.visit_id = v.id
    where v.status = 'ok' and v.bath_id in (select bath_id from doubt) group by 1, 2
    union all
    select l.bath_id, pl.id, sum(l.n)::int, max(l.year) from legacy_visits l join players pl on pl.nick = l.nick
    where l.bath_id in (select bath_id from doubt) group by 1, 2
  )
  select coalesce(jsonb_agg(jsonb_build_object('bath', w.bath_id, 'player', w.player_id, 'n', w.n, 'last', w.last)), '[]')
  from (select bath_id, player_id, sum(n)::int n, max(last) last from was group by 1, 2) w
$$;
revoke all on function public.point_ask_candidates() from public, anon, authenticated;
grant execute on function public.point_ask_candidates() to service_role;
