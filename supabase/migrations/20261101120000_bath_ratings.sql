-- Рейтинг бани (01.11, Леха): восемь пунктов — печь, пар, аквазона, выход на улицу, кухня, атмосфера, сервис, цены —
-- от 1 до 5 («в вениках», как звёзды в такси), все обязательные, вес одинаковый; общая — среднее восьми.
-- Оценивает только тот, кто был в походе: оценка привязана к засчитанному походу (с rating_since — с 01.11; по прошлым
-- разошлём отдельно). Рейтинг бани — по последней оценке каждого человека, чтобы частый гость не перевешивал.
-- Старые отзывы со «звездой» остаются отзывами, в рейтинг не входят.
create table public.bath_ratings (
  id bigint generated by default as identity primary key,
  visit_id bigint not null references public.visits(id) on delete cascade,
  bath_id bigint not null references public.baths(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  stove smallint not null check (stove between 1 and 5),            -- печь
  steam smallint not null check (steam between 1 and 5),            -- пар
  aqua smallint not null check (aqua between 1 and 5),              -- аквазона
  outdoor smallint not null check (outdoor between 1 and 5),        -- выход на улицу
  kitchen smallint not null check (kitchen between 1 and 5),        -- кухня
  atmosphere smallint not null check (atmosphere between 1 and 5),  -- атмосфера
  service smallint not null check (service between 1 and 5),        -- сервис
  prices smallint not null check (prices between 1 and 5),          -- цены
  overall numeric(3, 2) generated always as ((stove + steam + aqua + outdoor + kitchen + atmosphere + service + prices) / 8.0) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (visit_id, player_id)
);
create index on public.bath_ratings (bath_id, player_id, updated_at desc);
alter table public.bath_ratings enable row level security;
create policy "оценки видны всем" on public.bath_ratings for select using (true);
revoke insert, update, delete on public.bath_ratings from anon, authenticated;   -- пишет только rate_visit
grant select on public.bath_ratings to anon, authenticated;
grant all on public.bath_ratings to service_role;

insert into public.settings (key, value) values ('rating_since', '"2026-11-01"') on conflict (key) do nothing;

-- кому и когда бот пишет «оцени баню»: после «засчитано», напоминания через 3 и через 12 часов (ночью — нет, утром)
create table public.rating_asks (
  visit_id bigint not null references public.visits(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  stage smallint not null default 0,          -- сколько сообщений уже ушло: 0 — ни одного, 3 — всё, больше не пишем
  next_at timestamptz not null default now(),
  done boolean not null default false,        -- оценил (или писать некуда)
  primary key (visit_id, player_id)
);
alter table public.rating_asks enable row level security;
grant all on public.rating_asks to service_role;

-- что показать на странице оценки: баня, можно ли оценивать и прежняя оценка этого похода
create function public.rating_form(p_visit bigint) returns json
language sql stable security definer set search_path = public as $$
  select json_build_object('visit', v.id, 'bath', v.bath_id, 'name', b.name, 'entered_at', v.entered_at,
    'allowed', public.me() is not null and v.status = 'ok' and exists (select 1 from visit_players vp where vp.visit_id = v.id and vp.player_id = public.me())
      and v.entered_at >= (select (value #>> '{}')::date from settings where key = 'rating_since'),
    'why', case when public.me() is null then 'login'
                when not exists (select 1 from visit_players vp where vp.visit_id = v.id and vp.player_id = public.me()) then 'stranger'
                when v.status <> 'ok' then 'pending'
                when v.entered_at < (select (value #>> '{}')::date from settings where key = 'rating_since') then 'old' end,
    'scores', (select json_build_object('stove', r.stove, 'steam', r.steam, 'aqua', r.aqua, 'outdoor', r.outdoor, 'kitchen', r.kitchen,
                 'atmosphere', r.atmosphere, 'service', r.service, 'prices', r.prices)
               from bath_ratings r where r.visit_id = v.id and r.player_id = public.me()))
  from visits v join baths b on b.id = v.bath_id where v.id = p_visit
$$;
grant execute on function public.rating_form(bigint) to anon, authenticated, service_role;

-- поставить или поправить оценку своего засчитанного похода; все восемь пунктов — от 1 до 5
create function public.rate_visit(p_visit bigint, p_scores jsonb) returns numeric
language plpgsql security definer set search_path = public as $$
declare v visits; s int[]; k text; r numeric;
begin
  select * into v from visits where id = p_visit;
  if not found or v.status <> 'ok' then raise exception 'Оценить можно засчитанный поход'; end if;
  if public.me() is null or not exists (select 1 from visit_players where visit_id = p_visit and player_id = public.me()) then
    raise exception 'Оценивает тот, кто был в походе';
  end if;
  if v.entered_at < (select (value #>> '{}')::date from settings where key = 'rating_since') then raise exception 'Этот поход раньше рейтинга'; end if;
  foreach k in array array['stove', 'steam', 'aqua', 'outdoor', 'kitchen', 'atmosphere', 'service', 'prices'] loop
    if (p_scores ->> k) is null or (p_scores ->> k) !~ '^[1-5]$' then raise exception 'Нужны все восемь оценок от 1 до 5 (%)', k; end if;
    s := s || (p_scores ->> k)::int;
  end loop;
  insert into bath_ratings (visit_id, bath_id, player_id, stove, steam, aqua, outdoor, kitchen, atmosphere, service, prices)
  values (p_visit, v.bath_id, public.me(), s[1], s[2], s[3], s[4], s[5], s[6], s[7], s[8])
  on conflict (visit_id, player_id) do update set stove = excluded.stove, steam = excluded.steam, aqua = excluded.aqua,
    outdoor = excluded.outdoor, kitchen = excluded.kitchen, atmosphere = excluded.atmosphere, service = excluded.service,
    prices = excluded.prices, updated_at = now()
  returning overall into r;
  update rating_asks set done = true where visit_id = p_visit and player_id = public.me();
  return r;
end $$;
revoke execute on function public.rate_visit(bigint, jsonb) from public, anon;
grant execute on function public.rate_visit(bigint, jsonb) to authenticated, service_role;

-- рейтинг бань: последняя оценка каждого человека; общая и по пунктам. Одним json на все бани — для карты и карточки
create function public.bath_rating_all() returns json
language sql stable security definer set search_path = public as $$
  with last as (
    select distinct on (bath_id, player_id) * from bath_ratings order by bath_id, player_id, updated_at desc
  ), agg as (
    select bath_id, json_build_object('overall', round(avg(overall), 2), 'n', count(*),
      'stove', round(avg(stove), 1), 'steam', round(avg(steam), 1), 'aqua', round(avg(aqua), 1), 'outdoor', round(avg(outdoor), 1),
      'kitchen', round(avg(kitchen), 1), 'atmosphere', round(avg(atmosphere), 1), 'service', round(avg(service), 1),
      'prices', round(avg(prices), 1)) j
    from last group by bath_id
  )
  select coalesce(json_object_agg(bath_id, j), '{}') from agg
$$;
grant execute on function public.bath_rating_all() to anon, authenticated, service_role;

-- «засчитано» — каждому из компании в очередь «оцени баню» (походы с rating_since); бот разберёт её днём
create function public.queue_rating_asks() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'ok' and (tg_op = 'INSERT' or old.status is distinct from 'ok')
     and new.entered_at >= (select (value #>> '{}')::date from settings where key = 'rating_since') then
    insert into rating_asks (visit_id, player_id) select new.id, vp.player_id from visit_players vp where vp.visit_id = new.id
    on conflict do nothing;
  end if;
  return new;
end $$;
create trigger visits_rating_asks after insert or update of status on public.visits
for each row execute function public.queue_rating_asks();

-- участников похода записывают после самого похода — дописали в уже засчитанный: тоже в очередь
create function public.queue_rating_ask_player() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into rating_asks (visit_id, player_id)
  select new.visit_id, new.player_id from visits v where v.id = new.visit_id and v.status = 'ok'
    and v.entered_at >= (select (value #>> '{}')::date from settings where key = 'rating_since')
  on conflict do nothing;
  return new;
end $$;
create trigger visit_players_rating_asks after insert on public.visit_players
for each row execute function public.queue_rating_ask_player();

