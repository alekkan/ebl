#!/bin/sh
# Выкладывает и бэкенд, и сайт разом (18.10): проверки — один раз, потом миграции и функции, потом сайт.
# Раньше для этого запускали deploy-backend.sh и deploy.sh подряд, и каждый гонял полный check.sh (~10 минут) — выходило 20+.
# Гарантии те же: только из актуального main, без незакоммиченного, с зелёными проверками. Проверяется ровно тот коммит,
# что уедет: если за время проверок main на GitHub ушёл вперёд или коммит сменился, оба скрипта ниже остановятся сами
# (их _guard.sh сверяет main с GitHub), а между бэкендом и сайтом коммит сверяем здесь.
# Запуск: scripts/deploy-all.sh [функция ...]   — функции как у deploy-backend.sh (без аргументов — все).
set -e
cd "$(dirname "$0")/.."
. scripts/_guard.sh
commit=$(git rev-parse HEAD)
SKIP_CHECKS=1 scripts/deploy-backend.sh "$@"
[ "$(git rev-parse HEAD)" = "$commit" ] || { echo "Коммит сменился во время выкладки — сайт не выкладываю, запусти scripts/deploy.sh заново." >&2; exit 1; }
SKIP_CHECKS=1 scripts/deploy.sh
echo "Готово: и бэкенд, и сайт выложены (проверки — один раз, коммит $(git rev-parse --short HEAD))."
